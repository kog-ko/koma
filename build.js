const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const artworkDir = path.join(__dirname, 'artwork');
const outFile = path.join(__dirname, 'artwork.js');
const categories = ['analog', 'digital', 'game-dev'];
const validExtensions = ['.jpg', '.jpeg', '.png', '.webp', '.gif', '.mp4', '.mov', '.webm'];

// Dimensions let the page reserve space before media loads. They come from ffprobe
// when it's installed; otherwise from the previously generated artwork.js (so the
// build still works on hosts without ffprobe).
let previous = {};
try {
  const old = new Function(`${fs.readFileSync(outFile, 'utf8')}; return artwork;`)();
  old.forEach(p => { if (p.w && p.h) previous[p.file] = { w: p.w, h: p.h }; });
} catch (e) { /* first run */ }

function probe(fullPath, file) {
  try {
    const out = execFileSync('ffprobe', [
      '-v', 'error', '-select_streams', 'v:0',
      '-show_entries', 'stream=width,height', '-of', 'csv=p=0', fullPath
    ], { encoding: 'utf8' }).trim().split('\n')[0].split(',');
    const w = parseInt(out[0], 10), h = parseInt(out[1], 10);
    if (w > 0 && h > 0) return { w, h };
  } catch (e) { /* ffprobe missing or failed */ }
  return previous[file] || {};
}

const artwork = [];

categories.forEach(category => {
  const categoryDir = path.join(artworkDir, category);

  if (!fs.existsSync(categoryDir)) {
    fs.mkdirSync(categoryDir, { recursive: true });
    return;
  }

  fs.readdirSync(categoryDir).forEach(file => {
    const ext = path.extname(file).toLowerCase();
    if (!validExtensions.includes(ext)) return;

    const name = path.basename(file, ext);
    // Convert filename to title: "my-cool-art" -> "My Cool Art"
    const title = name
      .replace(/[-_]/g, ' ')
      .replace(/\b\w/g, c => c.toUpperCase());

    let medium = 'Image';
    if (['.mp4', '.mov', '.webm'].includes(ext)) medium = 'Video';
    else if (ext === '.gif') medium = 'GIF';

    const relFile = `artwork/${category}/${file}`;
    artwork.push({
      title,
      category,
      file: relFile,
      medium,
      ...probe(path.join(categoryDir, file), relFile)
    });
  });
});

// Group by category (in the order above), then by filename within each group
artwork.sort((a, b) =>
  categories.indexOf(a.category) - categories.indexOf(b.category) || a.file.localeCompare(b.file));

const output = `// Auto-generated by build.js - do not edit manually
const artwork = ${JSON.stringify(artwork, null, 2)};`;

fs.writeFileSync(outFile, output);
console.log(`Generated artwork.js with ${artwork.length} pieces`);
